#!/usr/bin/env python3
"""Write one run's randomised-colour PART scene (#212).

    python3 scripts/make_part_colour_scene.py              # draws a new seed
    python3 scripts/make_part_colour_scene.py --seed 777   # repeats a recorded one

Prints the path of a three-line child of scenes/FWDCenterLabSivaPoolRandom.yaml.
Start the simulator on that file (REACHY_SIM_SCENE=<path> ./scripts/start_sim.sh,
or native_mujoco/server.py --scene <path> --record runs).  Everything that loads
it, in the container too, then sees the same colours.

The seed is written in that file, and each run's manifest repeats it with the
colours it gave (`color_randomization`: the server's --record manifest and
generate_dataset's).  The file goes to scenes/generated/, which git ignores and
the container sees through its ./scenes mount.
"""

from __future__ import annotations

import argparse
import os
import pathlib
import secrets
import sys
from typing import Optional

_REPO = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_REPO / "native_mujoco"))

from scene_io import load_scene  # noqa: E402

PARENT = _REPO / "scenes" / "FWDCenterLabSivaPoolRandom.yaml"
#: Under scenes/ so docker compose's mount shows it to the container; ignored by git.
DEFAULT_OUT_DIR = _REPO / "scenes" / "generated"


def write_scene(seed: Optional[int] = None,
                out_dir: pathlib.Path = DEFAULT_OUT_DIR) -> pathlib.Path:
    """Write and check the child scene for `seed` (drawn when None)."""
    if seed is None:
        seed = secrets.randbits(32)
    out_dir = pathlib.Path(out_dir).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"FWDCenterLabSivaPoolRandom_seed{seed}.yaml"
    text = ("# Generated by scripts/make_part_colour_scene.py.  Do not commit or edit.\n"
            'schema_version: "1.0"\n'
            f"extends: {os.path.relpath(PARENT, out_dir)}\n"
            f"color_randomization: {{seed: {int(seed)}}}\n")
    # Check the seed before leaving a file behind.
    fresh = not path.exists()
    path.write_text(text)
    try:
        load_scene(path)
    except Exception:
        if fresh:
            path.unlink()
        raise
    return path


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed", type=int, default=None, help="0..2^32-1; drawn if omitted")
    ap.add_argument("--out-dir", type=pathlib.Path, default=DEFAULT_OUT_DIR)
    args = ap.parse_args()
    print(write_scene(args.seed, args.out_dir))
    return 0


if __name__ == "__main__":
    sys.exit(main())
